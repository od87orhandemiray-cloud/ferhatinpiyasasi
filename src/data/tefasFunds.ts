// Helper to generate realistic historical price curve
function generateFundHistory(basePrice: number, change1Y: number, volatility: number) {
  const points = 30; // 30 data points for smooth line
  const history = [];
  const startPrice = basePrice / (1 + change1Y / 100);
  const now = new Date();

  for (let i = 0; i <= points; i++) {
    const d = new Date(now);
    d.setDate(d.getDate() - (points - i) * 12); // over ~360 days
    const progress = i / points;
    // trend + noise
    const noise = (Math.sin(i * 1.5) * 0.4 + Math.cos(i * 2.8) * 0.3) * (volatility / 10);
    const simulatedPrice = startPrice + (basePrice - startPrice) * Math.pow(progress, 1.1) + startPrice * noise;
    const bistProgress = startPrice * (1 + 0.58 * progress + (Math.sin(i) * 0.05));
    const goldProgress = startPrice * (1 + 0.68 * progress + (Math.cos(i * 0.8) * 0.04));

    history.push({
      date: d.toLocaleDateString('tr-TR', { day: 'numeric', month: 'short' }),
      price: Number(Math.max(0.01, simulatedPrice).toFixed(4)),
      bistReturn: Number((((bistProgress - startPrice) / startPrice) * 100).toFixed(1)),
      goldReturn: Number((((goldProgress - startPrice) / startPrice) * 100).toFixed(1)),
    });
  }
  // Ensure last point is exactly basePrice
  if (history.length > 0) {
    history[history.length - 1].price = basePrice;
  }
  return history;
}

